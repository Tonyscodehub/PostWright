"""Drives the webmail page in Chromium: sign in, read, reply, calendar, contacts. Saves screenshots."""
import sys, time
from playwright.sync_api import sync_playwright
R = []; errors = []
def check(n, c, i=""):
    R.append(bool(c)); print(("PASS " if c else "FAIL ") + n + (f"  [{str(i)[:300]}]" if i and not c else ""))
OUT = "/home/claude/shots/wm"
with sync_playwright() as p:
    b = p.chromium.launch()
    pg = b.new_page(ignore_https_errors=True, viewport={"width": 1440, "height": 900})
    pg.on("pageerror", lambda e: errors.append(str(e)))
    pg.on("console", lambda m: m.type == "error" and errors.append(m.text))
    pg.on("dialog", lambda d: d.accept())
    pg.goto("https://127.0.0.1:8443/")
    pg.fill("#email", "tony@johncock.test"); pg.fill("#password", "CorrectHorse1"); pg.click("#go")
    pg.wait_for_selector("#folders li", timeout=10000)
    pg.wait_for_selector("#msgs .msg", timeout=10000)
    check("signs in to the webmail", "Inbox" in pg.inner_text("#folders"))
    pg.screenshot(path=f"{OUT}/1-inbox.png")
    # Open the forwarded message
    pg.click("#msgs .msg >> nth=0")
    pg.wait_for_selector("#read-body h1", timeout=10000)
    time.sleep(0.8)
    check("message opens in the reading pane", pg.inner_text("#read-body h1") != "")
    pg.screenshot(path=f"{OUT}/2-read.png")
    # Reply
    pg.click("#r-reply")
    pg.wait_for_selector("#compose:not(.hidden)")
    check("reply prefills recipient and subject", pg.input_value("#c-subject").startswith("Re:") and pg.locator("#c-to .chip").count() == 1, pg.input_value("#c-subject"))
    pg.click("#editor"); pg.keyboard.press("Control+Home"); pg.keyboard.type("Sounds good, see you then.")
    pg.screenshot(path=f"{OUT}/3-compose.png")
    pg.click("#c-send")
    pg.wait_for_selector("#toast:not(.hidden)", timeout=10000)
    check("reply sent", "Sent" in pg.inner_text("#toast"), pg.inner_text("#toast"))
    # New message with autocomplete
    pg.click("#new-msg")
    pg.click("#c-to"); pg.keyboard.type("amy")
    time.sleep(0.6)
    sug = pg.locator(".suggest div").count()
    pg.keyboard.press("Enter") if sug else pg.keyboard.type("@poffles.test,")
    pg.fill("#c-subject", "Webmail test from the browser")
    pg.click("#editor"); pg.keyboard.type("Hello from Postwright webmail.")
    pg.click("#c-save")
    pg.wait_for_selector("#c-status:has-text('Draft saved')", timeout=10000)
    check("draft saves", True)
    pg.click("#c-send")
    pg.wait_for_selector("#toast:has-text('Sent')", timeout=10000)
    check("new message sent", True)
    # Sent folder
    pg.click("#folders li:has-text('Sent')")
    pg.wait_for_selector("#msgs .msg:has-text('Webmail test from the browser')", timeout=10000)
    check("sent message appears in Sent", True)
    # Calendar week + month
    pg.click("#apps button[data-app=cal]")
    pg.wait_for_selector(".week, .month", timeout=10000)
    time.sleep(0.5)
    pg.screenshot(path=f"{OUT}/4-week.png")
    pg.click("#new-ev")
    pg.wait_for_selector(".dialog")
    pg.fill(".dialog input[placeholder='Add a title']", "Browser-made meeting")
    pg.fill(".dialog input[placeholder='Add a place or a meeting link']", "Office")
    pg.screenshot(path=f"{OUT}/5-event.png")
    pg.click(".dialog .btn.ok")
    pg.wait_for_selector(".blk:has-text('Browser-made meeting'), .ev:has-text('Browser-made meeting')", timeout=10000)
    check("event created from the calendar", True)
    pg.click("#c-views button[data-v=month]")
    pg.wait_for_selector(".month")
    pg.click("#c-next"); pg.wait_for_selector(".month"); time.sleep(0.5)
    check("month view shows the weekly meeting chips", pg.locator(".ev").count() > 0)
    pg.screenshot(path=f"{OUT}/6-month.png")
    # Contacts
    pg.click("#apps button[data-app=contacts]")
    pg.click("#new-ct")
    pg.wait_for_selector(".dialog")
    inputs = pg.locator(".dialog input[type=text]")
    inputs.nth(0).fill("Penny Lane"); inputs.nth(1).fill("penny@lane.example"); inputs.nth(2).fill("01632 960000")
    pg.click(".dialog .btn.ok")
    pg.wait_for_selector("#ct-detail h1:has-text('Penny Lane')", timeout=10000)
    check("contact created", True)
    pg.screenshot(path=f"{OUT}/7-contacts.png")
    # Narrow screen
    m = b.new_page(ignore_https_errors=True, viewport={"width": 390, "height": 844}, storage_state=pg.context.storage_state())
    m.goto("https://127.0.0.1:8443/#mail")
    m.wait_for_selector("#msgs .msg", timeout=10000)
    m.screenshot(path=f"{OUT}/8-phone-list.png")
    m.click("#msgs .msg >> nth=0"); m.wait_for_selector("#read-body h1"); time.sleep(0.5)
    check("phone layout shows one pane at a time", m.is_visible("#read") and not m.is_visible("#list"))
    m.screenshot(path=f"{OUT}/9-phone-read.png")
    check("no script errors", not errors, errors)
    b.close()
print(f"\n{sum(R)}/{len(R)} passed"); sys.exit(0 if all(R) else 1)
